/// <summary>Resolves library-owned template text when its target is created, after the host loads its language.</summary>
public sealed class InteractiveLabelExtension(string key) : MarkupExtension
{
    public string Value
    {
        get
        {
            var value = InteractiveLabels.Current[key];
            return OperatingSystem.IsMacOS()
                ? value.Replace("Ctrl+", "⌘").Replace("Shift+", "⇧").Replace("Alt+", "⌥").Replace("Win+", "⌘")
                : value;
        }
    }

    // The typed getter keeps deferred labels trim/AOT-safe without reflection.
    public override object ProvideValue(IServiceProvider serviceProvider) =>
        new CompiledBindingExtension(
            new CompiledBindingPathBuilder()
                .Property(
                    new ClrPropertyInfo(nameof(Value), static source => ((InteractiveLabelExtension)source).Value,
                        null, typeof(string)),
                    PropertyInfoAccessorFactory.CreateInpcPropertyAccessor)
                .Build())
        {
            Source = this,
            Mode = BindingMode.OneTime
        };
}
